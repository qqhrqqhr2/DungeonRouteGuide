def sewer_px(x, y):
    return (round((x - SEWER_X0) * 2), round((SEWER_YTOP - y) * 2))


def sewer_tiles():
    out = []
    for layer, (g, mx, my, blocks) in enumerate(SEWER_GROUPS):
        for bx, by, fid, w, h in blocks:
            out.append((fid, *sewer_px(mx + 128 * bx, my + 128 * by + h / 2), w, h, layer))
    return out


